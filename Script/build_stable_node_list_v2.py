#!/usr/bin/env python3
"""Build stable modelling node lists from the v2 speed data audit.

This script uses the v2 node coverage report, where no-vehicle intervals and
true raw-missing intervals are separated. It therefore avoids treating
low-flow no-vehicle periods as raw sensor missingness.

The original v1 stable-node script is left unchanged for traceability.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict, dataclass
from pathlib import Path

import pandas as pd


DEFAULT_COUNTLINE_METADATA = Path("data_external/countlines/countline_nottingham.csv")


def dataframe_to_markdown(df: pd.DataFrame) -> str:
    """Render a small DataFrame as a markdown table without optional packages."""
    if df.empty:
        return "_No rows._"

    display = df.copy()
    for col in display.columns:
        if pd.api.types.is_float_dtype(display[col]):
            display[col] = display[col].map(lambda value: "" if pd.isna(value) else f"{value:.4f}")
        else:
            display[col] = display[col].map(lambda value: "" if pd.isna(value) else str(value))

    headers = [str(col) for col in display.columns]
    rows = display.astype(str).values.tolist()
    widths = [len(header) for header in headers]
    for row in rows:
        widths = [max(width, len(cell)) for width, cell in zip(widths, row)]

    def format_row(row_values: list[str]) -> str:
        return "| " + " | ".join(cell.ljust(width) for cell, width in zip(row_values, widths)) + " |"

    separator = ["-" * width for width in widths]
    return "\n".join([format_row(headers), format_row(separator), *(format_row(row) for row in rows)])


@dataclass(frozen=True)
class SelectionRule:
    name: str
    require_all_days: bool = True
    min_observed_speed_rate_present_days: float | None = None
    max_raw_missing_rate_present_days: float | None = None
    min_total_motorised_count: int | None = None


RULES = [
    SelectionRule("present_all_days_only"),
    SelectionRule("present_all_days_observed_ge_10pct", min_observed_speed_rate_present_days=0.10),
    SelectionRule("present_all_days_observed_ge_20pct", min_observed_speed_rate_present_days=0.20),
    SelectionRule("present_all_days_observed_ge_30pct", min_observed_speed_rate_present_days=0.30),
    SelectionRule("present_all_days_observed_ge_40pct", min_observed_speed_rate_present_days=0.40),
    SelectionRule("present_all_days_observed_ge_50pct", min_observed_speed_rate_present_days=0.50),
    SelectionRule("present_all_days_observed_ge_60pct", min_observed_speed_rate_present_days=0.60),
    SelectionRule("present_all_days_observed_ge_70pct", min_observed_speed_rate_present_days=0.70),
    SelectionRule("present_all_days_observed_ge_80pct", min_observed_speed_rate_present_days=0.80),
    SelectionRule("present_all_days_observed_ge_90pct", min_observed_speed_rate_present_days=0.90),
    SelectionRule("present_all_days_raw_missing_le_5pct", max_raw_missing_rate_present_days=0.05),
    SelectionRule("present_all_days_count_ge_100000", min_total_motorised_count=100_000),
    SelectionRule(
        "present_all_days_observed_ge_50pct_count_ge_100000",
        min_observed_speed_rate_present_days=0.50,
        min_total_motorised_count=100_000,
    ),
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--coverage-report",
        type=Path,
        default=Path("data_processed/speed/audit_v2/v2_node_coverage_report.csv"),
        help="v2 node coverage report generated by build_processed_speed_data_audit_v2.py.",
    )
    parser.add_argument(
        "--countline-metadata",
        type=Path,
        default=DEFAULT_COUNTLINE_METADATA,
        help="Optional countline metadata CSV with coordinates and is_speed flags.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("data_processed/speed/node_selection_v2"),
        help="Output folder for v2 stable-node files.",
    )
    parser.add_argument(
        "--tables-dir",
        type=Path,
        default=Path("outputs/tables"),
        help="Folder for copies of key human-readable tables.",
    )
    parser.add_argument(
        "--default-rule",
        default="present_all_days_observed_ge_50pct",
        choices=[rule.name for rule in RULES],
        help="Rule used for stable_node_list_v2.csv.",
    )
    return parser.parse_args()


def load_countline_metadata(path: Path) -> pd.DataFrame | None:
    if not path.exists():
        return None
    meta = pd.read_csv(path)
    if "id" not in meta.columns:
        return None

    keep_cols = [
        col
        for col in [
            "id",
            "name",
            "description",
            "direction",
            "is_dwell_times_filtering_countline",
            "is_anpr",
            "is_speed",
            "start_lat",
            "start_long",
            "end_lat",
            "end_long",
            "mean_lat",
            "mean_lon",
        ]
        if col in meta.columns
    ]
    meta = meta[keep_cols].copy()
    meta = meta.rename(columns={"id": "Countline", "direction": "metadata_direction"})
    meta["Countline"] = pd.to_numeric(meta["Countline"], errors="coerce")
    meta = meta[meta["Countline"].notna()].copy()
    meta["Countline"] = meta["Countline"].astype("int64")
    return meta.drop_duplicates("Countline")


def add_direction_consistency_flags(data: pd.DataFrame) -> pd.DataFrame:
    result = data.copy()
    if "metadata_direction" not in result.columns:
        result["direction_metadata_check"] = "metadata_not_available"
        return result

    result["direction_metadata_check"] = "consistent_or_bidirectional"
    result.loc[
        result["metadata_direction"].eq("ANTICLOCKWISE_ONLY") & result["Direction"].eq("clockwise"),
        "direction_metadata_check",
    ] = "metadata_anticlockwise_only_but_processed_clockwise"
    result.loc[
        result["metadata_direction"].eq("CLOCKWISE_ONLY") & result["Direction"].eq("anti_clockwise"),
        "direction_metadata_check",
    ] = "metadata_clockwise_only_but_processed_anti_clockwise"
    result.loc[result["metadata_direction"].isna(), "direction_metadata_check"] = "metadata_direction_missing"
    return result


def apply_rule(coverage: pd.DataFrame, rule: SelectionRule) -> pd.Series:
    selected = pd.Series(True, index=coverage.index)
    if rule.require_all_days:
        selected &= coverage["missing_days"].eq(0)
    if rule.min_observed_speed_rate_present_days is not None:
        selected &= coverage["observed_speed_rate_present_days"].ge(
            rule.min_observed_speed_rate_present_days
        )
    if rule.max_raw_missing_rate_present_days is not None:
        selected &= coverage["raw_missing_rate_present_days"].le(rule.max_raw_missing_rate_present_days)
    if rule.min_total_motorised_count is not None:
        selected &= coverage["total_motorised_count"].ge(rule.min_total_motorised_count)
    return selected


def add_selection_flags(coverage: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    result = coverage.copy()
    rows = []
    for rule in RULES:
        flag = apply_rule(result, rule)
        result[f"selected_{rule.name}"] = flag
        selected = result[flag]
        rows.append(
            {
                "rule": rule.name,
                "rule_definition": json.dumps(asdict(rule), ensure_ascii=False),
                "selected_nodes": len(selected),
                "selected_countlines": selected["Countline"].nunique(),
                "mean_observed_speed_rate_present_days": selected[
                    "observed_speed_rate_present_days"
                ].mean()
                if len(selected)
                else pd.NA,
                "mean_no_vehicle_rate_present_days": selected[
                    "no_vehicle_rate_present_days"
                ].mean()
                if len(selected)
                else pd.NA,
                "mean_raw_missing_rate_present_days": selected[
                    "raw_missing_rate_present_days"
                ].mean()
                if len(selected)
                else pd.NA,
                "min_total_motorised_count": selected["total_motorised_count"].min()
                if len(selected)
                else pd.NA,
                "median_total_motorised_count": selected["total_motorised_count"].median()
                if len(selected)
                else pd.NA,
                "total_motorised_count": selected["total_motorised_count"].sum()
                if len(selected)
                else 0,
            }
        )
    return result, pd.DataFrame(rows)


def build_stable_nodes(coverage: pd.DataFrame, default_rule: str) -> pd.DataFrame:
    flag_col = f"selected_{default_rule}"
    stable = coverage[coverage[flag_col]].copy().sort_values("node_id").reset_index(drop=True)
    stable["stable_rule"] = default_rule
    stable["node_order"] = range(len(stable))

    base_cols = [
        "node_order",
        "node_id",
        "Countline",
        "Direction",
        "stable_rule",
        "days_present",
        "missing_days",
        "node_presence_rate",
        "observed_speed_rate_present_days",
        "no_vehicle_rate_present_days",
        "raw_missing_rate_present_days",
        "observed_speed_rate_expected_period",
        "total_motorised_count",
        "mean_observed_speed",
        "median_observed_speed",
        "car_share_total",
        "bus_minibus_share_total",
        "heavy_goods_share_total",
        "van_share_total",
        "taxi_share_total",
        "motorbike_share_total",
        "direction_metadata_check",
    ]
    optional_cols = [
        "name",
        "metadata_direction",
        "is_speed",
        "is_anpr",
        "mean_lat",
        "mean_lon",
        "start_lat",
        "start_long",
        "end_lat",
        "end_long",
    ]
    selected_cols = base_cols + [col for col in optional_cols if col in stable.columns]
    return stable[selected_cols]


def build_direction_report(coverage: pd.DataFrame, default_rule: str) -> pd.DataFrame:
    flag_col = f"selected_{default_rule}"
    group_cols = ["direction_metadata_check"]
    if "metadata_direction" in coverage.columns:
        group_cols.append("metadata_direction")
    group_cols.append("Direction")
    return (
        coverage.groupby(group_cols, dropna=False)
        .agg(nodes=("node_id", "count"), selected_default=(flag_col, "sum"))
        .reset_index()
    )


def write_summary(
    output_dir: Path,
    coverage: pd.DataFrame,
    stable_nodes: pd.DataFrame,
    rule_summary: pd.DataFrame,
    default_rule: str,
    metadata_path: Path,
) -> None:
    lines = [
        "# Stable Node Selection Summary v2",
        "",
        "## Basis",
        "",
        "- Source: `data_processed/speed/audit_v2/v2_node_coverage_report.csv`.",
        "- v2 distinguishes `observed`, `no_vehicle_observed`, and `raw_missing_or_not_reported` intervals.",
        "- No-vehicle intervals are not treated as raw data missingness.",
        f"- Countline metadata used: `{metadata_path}`" if metadata_path.exists() else "- Countline metadata not found.",
        "",
        "## Default Selection",
        "",
        f"- Default rule: `{default_rule}`",
        f"- Stable nodes selected: {len(stable_nodes):,}",
        f"- Stable countlines selected: {stable_nodes['Countline'].nunique():,}",
        f"- All candidate nodes in v2 coverage report: {len(coverage):,}",
        f"- Candidate nodes present on all days: {int(coverage['missing_days'].eq(0).sum()):,}",
        "",
        "## Rule Comparison",
        "",
        dataframe_to_markdown(rule_summary),
        "",
        "## Interpretation",
        "",
        (
            "The default v2 rule is intentionally based on observed speed availability and node "
            "presence, not on a generic missing-speed rate. This is because many null speed values "
            "represent valid no-vehicle intervals rather than raw sensor dropouts."
        ),
        "",
        "## Output Files",
        "",
        "- `v2_node_coverage_report_with_selection.csv`: all nodes with v2 selection flags.",
        "- `stable_node_list_v2.csv`: default selected modelling nodes.",
        "- `v2_node_selection_rule_summary.csv`: comparison of candidate selection rules.",
        "- `direction_metadata_consistency_report_v2.csv`: processed direction versus metadata direction checks.",
    ]
    (output_dir / "stable_node_selection_summary_v2.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    args.tables_dir.mkdir(parents=True, exist_ok=True)

    coverage = pd.read_csv(args.coverage_report)
    meta = load_countline_metadata(args.countline_metadata)
    if meta is not None:
        coverage = coverage.merge(meta, on="Countline", how="left")
    coverage = add_direction_consistency_flags(coverage)

    coverage, rule_summary = add_selection_flags(coverage)
    stable_nodes = build_stable_nodes(coverage, args.default_rule)
    direction_report = build_direction_report(coverage, args.default_rule)

    outputs = {
        "v2_node_coverage_report_with_selection.csv": coverage,
        "stable_node_list_v2.csv": stable_nodes,
        "v2_node_selection_rule_summary.csv": rule_summary,
        "direction_metadata_consistency_report_v2.csv": direction_report,
    }
    for filename, df in outputs.items():
        df.to_csv(args.output_dir / filename, index=False)
        df.to_csv(args.tables_dir / filename, index=False)

    write_summary(
        output_dir=args.output_dir,
        coverage=coverage,
        stable_nodes=stable_nodes,
        rule_summary=rule_summary,
        default_rule=args.default_rule,
        metadata_path=args.countline_metadata,
    )

    print(f"Default rule: {args.default_rule}")
    print(f"Total candidate nodes: {len(coverage)}")
    print(f"Stable nodes: {len(stable_nodes)}")
    print(f"Stable countlines: {stable_nodes['Countline'].nunique()}")
    print(f"Outputs written to: {args.output_dir}")


if __name__ == "__main__":
    main()
