def load_nodes(path: Path) -> pd.DataFrame:
    nodes = pd.read_csv(path)
    missing = [col for col in REQUIRED_NODE_COLUMNS if col not in nodes.columns]
    if missing:
        raise ValueError(f"Node list is missing required columns: {missing}")

    nodes = nodes.copy()
    nodes["node_order"] = pd.to_numeric(nodes["node_order"], errors="raise").astype(int)
    nodes = nodes.sort_values("node_order").reset_index(drop=True)
    expected = list(range(len(nodes)))
    if nodes["node_order"].tolist() != expected:
        raise ValueError("node_order must be consecutive integers starting from 0.")
    if nodes["node_id"].duplicated().any():
        dupes = nodes.loc[nodes["node_id"].duplicated(), "node_id"].tolist()
        raise ValueError(f"Duplicate node_id values in node list: {dupes[:5]}")
    return nodes


def expected_timestamps(start_date: str, end_date: str, frequency: str) -> pd.DatetimeIndex:
    start = pd.Timestamp(start_date)
    end = pd.Timestamp(end_date) + pd.Timedelta(days=1) - pd.Timedelta(frequency)
    return pd.date_range(start=start, end=end, freq=frequency)


def filter_timestamps(
    timestamps: pd.DatetimeIndex,
    exclude_weekends: bool,
    exclude_bank_holidays: bool,
    bank_holidays: list[str],
) -> tuple[pd.DatetimeIndex, dict[str, object]]:
    """Optionally filter the model timestamp grid by calendar date."""

    keep = pd.Series(True, index=timestamps)
    bank_holiday_dates = {pd.Timestamp(date).date() for date in bank_holidays}

    if exclude_weekends:
        keep &= timestamps.dayofweek < 5
    if exclude_bank_holidays:
        keep &= ~pd.Series(timestamps.date, index=timestamps).isin(bank_holiday_dates)

    filtered = timestamps[keep.to_numpy()]
    removed = timestamps[~keep.to_numpy()]
    removed_days = sorted({ts.date().isoformat() for ts in removed})

    return filtered, {
        "original_timestamps": len(timestamps),
        "filtered_timestamps": len(filtered),
        "removed_timestamps": len(removed),
        "original_days": len(pd.Index(timestamps.date).unique()),
        "filtered_days": len(pd.Index(filtered.date).unique()),
        "removed_days": removed_days,
        "exclude_weekends": exclude_weekends,
        "exclude_bank_holidays": exclude_bank_holidays,
        "bank_holidays": sorted(date.isoformat() for date in bank_holiday_dates),
    }


def statistics_timestamps(
    start_date: str | None,
    end_date: str | None,
    frequency: str,
    output_timestamps: pd.DatetimeIndex,
    exclude_weekends: bool,
    exclude_bank_holidays: bool,
    bank_holidays: list[str],
    label: str,
) -> pd.DatetimeIndex | None:
    """Build an optional timestamp grid for training-only statistic estimates."""

    if not start_date and not end_date:
        return None
    if not start_date or not end_date:
        raise ValueError(f"Both {label} start and end dates are required when using a separate statistics period.")

    all_stats_timestamps = expected_timestamps(start_date, end_date, frequency)
    stats_timestamps, _ = filter_timestamps(
        all_stats_timestamps,
        exclude_weekends=exclude_weekends,
        exclude_bank_holidays=exclude_bank_holidays,
        bank_holidays=bank_holidays,
    )
    stats_timestamps = stats_timestamps.intersection(output_timestamps)
    if stats_timestamps.empty:
        raise ValueError(f"The {label} statistics period has no overlap with the output timestamp grid.")
    return stats_timestamps


def read_daily_files(input_dir: Path, start_date: str, end_date: str) -> pd.DataFrame:
    dates = pd.date_range(start=start_date, end=end_date, freq="D")
    frames = []
    missing_files = []
    for date in dates:
        path = input_dir / f"speed_{date.date()}_5min_node_level.csv"
        if not path.exists():
            missing_files.append(path.name)
            continue
        data = pd.read_csv(path)
        missing_cols = [col for col in REQUIRED_SPEED_COLUMNS if col not in data.columns]
        if missing_cols:
            raise ValueError(f"{path} is missing required columns: {missing_cols}")
        frames.append(data[REQUIRED_SPEED_COLUMNS].copy())

    if missing_files:
        raise FileNotFoundError(
            f"Missing {len(missing_files)} daily files, first examples: {missing_files[:5]}"
        )
    if not frames:
        raise FileNotFoundError(f"No daily speed files found in {input_dir}")

    combined = pd.concat(frames, ignore_index=True)
    combined["time_5min"] = pd.to_datetime(combined["time_5min"])
    return combined


def pivot_matrix(
    data: pd.DataFrame,
    timestamps: pd.DatetimeIndex,
    node_ids: list[str],
    value_col: str,
    fill_value: float | int | None = None,
) -> pd.DataFrame:
    matrix = (
        data.pivot_table(index="time_5min", columns="node_id", values=value_col, aggfunc="first")
        .reindex(index=timestamps, columns=node_ids)
        .sort_index()
    )
    if fill_value is not None:
        matrix = matrix.fillna(fill_value)
    return matrix


def _short_missing_mask(missing: pd.Series, max_gap: int) -> pd.Series:
    """Return True only for missing runs whose consecutive length is <= max_gap."""

    if max_gap < 1:
        return pd.Series(False, index=missing.index)
    groups = missing.ne(missing.shift(fill_value=False)).cumsum()
    run_lengths = missing.groupby(groups).transform("sum")
    return missing & (run_lengths <= max_gap)


def fill_short_linear_gaps(speed: pd.DataFrame, max_linear_gap: int) -> pd.DataFrame:
    linear_candidate = speed.interpolate(method="time", limit_direction="both")
    filled = speed.copy()
    for col in speed.columns:
        short_gap = _short_missing_mask(speed[col].isna(), max_linear_gap)
        use = short_gap & linear_candidate[col].notna()
        if use.any():
            filled.loc[use, col] = linear_candidate.loc[use, col]
    return filled


def interpolate_speed_matrix(
    speed: pd.DataFrame,
    max_linear_gap: int,
    outlier_mask: pd.DataFrame | None = None,
    imputation_stats_timestamps: pd.DatetimeIndex | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return fully numeric speed matrix and an imputation method matrix.

    Method codes:
    - observed: original non-missing speed
    - short_gap_linear_interpolation: short missing runs filled by linear interpolation
    - time_of_day_node_median: longer missing runs filled by node-specific time-of-day median
    - node_median: final fallback filled by node median
    - global_median: final fallback if a node median is unavailable
    """

    method = pd.DataFrame("observed", index=speed.index, columns=speed.columns)
    if outlier_mask is not None:
        method[outlier_mask] = "iqr_outlier_removed"

    linear_candidate = speed.interpolate(method="time", limit_direction="both")
    filled = speed.copy()
    for col in speed.columns:
        short_gap = _short_missing_mask(speed[col].isna(), max_linear_gap)
        use = short_gap & linear_candidate[col].notna()
        if use.any():
            filled.loc[use, col] = linear_candidate.loc[use, col]
            method.loc[use, col] = "short_gap_linear_interpolation"
            if outlier_mask is not None:
                outlier_use = use & outlier_mask[col]
                method.loc[outlier_use, col] = "iqr_outlier_removed_then_linear_interpolation"

    if imputation_stats_timestamps is None:
        median_source = filled
    else:
        stats_index = speed.index.intersection(imputation_stats_timestamps)
        if stats_index.empty:
            raise ValueError("No imputation statistics timestamps overlap with the output speed matrix.")
        median_source = fill_short_linear_gaps(speed.loc[stats_index], max_linear_gap)
        if median_source.notna().to_numpy().sum() == 0:
            raise ValueError("No non-missing speed values are available for median imputation statistics.")

    still_missing = filled.isna()
    if still_missing.any().any():
        source_time_keys = median_source.index.strftime("%H:%M")
        for col in filled.columns:
            col_missing = filled[col].isna()
            if not col_missing.any():
                continue
            if imputation_stats_timestamps is None:
                medians = filled[col].groupby(source_time_keys).transform("median")
            else:
                medians_by_time = median_source[col].groupby(source_time_keys).median()
                medians = pd.Series(filled.index.strftime("%H:%M"), index=filled.index).map(medians_by_time)
            use = col_missing & medians.notna()
            filled.loc[use, col] = medians[use]
            method.loc[use, col] = "time_of_day_node_median"
            if outlier_mask is not None:
                outlier_use = use & outlier_mask[col]
                method.loc[outlier_use, col] = "iqr_outlier_removed_then_time_of_day_node_median"

    still_missing = filled.isna()
    if still_missing.any().any():
        node_medians = median_source.median(axis=0, skipna=True)
        for col in filled.columns:
            use = filled[col].isna() & pd.notna(node_medians[col])
            if use.any():
                filled.loc[use, col] = node_medians[col]
                method.loc[use, col] = "node_median"
                if outlier_mask is not None:
                    outlier_use = use & outlier_mask[col]
                    method.loc[outlier_use, col] = "iqr_outlier_removed_then_node_median"

    still_missing = filled.isna()
    if still_missing.any().any():
        global_median = float(np.nanmedian(median_source.to_numpy(dtype=float)))
        filled = filled.fillna(global_median)
        method[still_missing] = "global_median"
        if outlier_mask is not None:
            outlier_use = still_missing & outlier_mask
            method[outlier_use] = "iqr_outlier_removed_then_global_median"

    return filled, method


def detect_upper_iqr_outliers(
    speed: pd.DataFrame,
    iqr_multiplier: float,
    min_observations: int,
    stats_timestamps: pd.DatetimeIndex | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Detect conservative node-wise upper speed outliers.

    Only upper outliers are removed because very low speeds may represent real
    congestion rather than data errors. The filtered speed matrix keeps the
    original shape and replaces outlier cells with missing values. If
    stats_timestamps is provided, node-wise IQR thresholds are estimated only
    from that period and then applied to the full speed matrix.
    """

    filtered = speed.copy()
    outlier_mask = pd.DataFrame(False, index=speed.index, columns=speed.columns)
    audit_rows: list[dict[str, object]] = []
    cell_rows: list[dict[str, object]] = []
    stats_index = speed.index if stats_timestamps is None else speed.index.intersection(stats_timestamps)
    if stats_index.empty:
        raise ValueError("No IQR statistics timestamps overlap with the output speed matrix.")

    for node_id in speed.columns:
        series = speed[node_id]
        stats_valid = series.loc[stats_index].dropna()
        valid = series.dropna()
        stats_observations = int(stats_valid.shape[0])
        observations = int(valid.shape[0])

        if stats_observations < min_observations:
            audit_rows.append(
                {
                    "node_id": node_id,
                    "observed_values": observations,
                    "stats_observed_values": stats_observations,
                    "q1": np.nan,
                    "q3": np.nan,
                    "iqr": np.nan,
                    "iqr_multiplier": iqr_multiplier,
                    "upper_bound": np.nan,
                    "outlier_count": 0,
                    "outlier_rate_observed": 0.0,
                    "max_original_speed": float(valid.max()) if observations else np.nan,
                    "status": "skipped_insufficient_observations",
                }
            )
            continue

        q1 = float(stats_valid.quantile(0.25))
        q3 = float(stats_valid.quantile(0.75))
        iqr = q3 - q1
        max_original_speed = float(valid.max())

        if iqr <= 0 or np.isnan(iqr):
            audit_rows.append(
                {
                    "node_id": node_id,
                    "observed_values": observations,
                    "stats_observed_values": stats_observations,
                    "q1": q1,
                    "q3": q3,
                    "iqr": iqr,
                    "iqr_multiplier": iqr_multiplier,
                    "upper_bound": np.nan,
                    "outlier_count": 0,
                    "outlier_rate_observed": 0.0,
                    "max_original_speed": max_original_speed,
                    "status": "skipped_non_positive_iqr",
                }
            )
            continue

        upper_bound = q3 + iqr_multiplier * iqr
        node_outliers = series > upper_bound
        outlier_count = int(node_outliers.sum())
        outlier_mask.loc[node_outliers, node_id] = True
        filtered.loc[node_outliers, node_id] = np.nan

        audit_rows.append(
            {
                "node_id": node_id,
                "observed_values": observations,
                "stats_observed_values": stats_observations,
                "q1": q1,
                "q3": q3,
                "iqr": iqr,
                "iqr_multiplier": iqr_multiplier,
                "upper_bound": upper_bound,
                "outlier_count": outlier_count,
                "outlier_rate_observed": outlier_count / observations,
                "max_original_speed": max_original_speed,
                "status": "applied",
            }
        )

        if outlier_count:
            outlier_values = series.loc[node_outliers]
            for timestamp, original_speed in outlier_values.items():
                cell_rows.append(
                    {
                        "datetime": timestamp.strftime("%Y-%m-%d %H:%M:%S"),
                        "node_id": node_id,
                        "original_speed": float(original_speed),
                        "q1": q1,
                        "q3": q3,
                        "iqr": iqr,
                        "iqr_multiplier": iqr_multiplier,
                        "upper_bound": upper_bound,
                    }
                )

    audit = pd.DataFrame(audit_rows)
    cells = pd.DataFrame(
        cell_rows,
        columns=[
            "datetime",
            "node_id",
            "original_speed",
            "q1",
            "q3",
            "iqr",
            "iqr_multiplier",
            "upper_bound",
        ],
    )
    return filtered, outlier_mask, audit, cells


def add_datetime_column(matrix: pd.DataFrame) -> pd.DataFrame:
    out = matrix.copy()
    out.insert(0, "datetime", out.index.strftime("%Y-%m-%d %H:%M:%S"))
    return out


def build_run_summary(
    nodes: pd.DataFrame,
    timestamps: pd.DatetimeIndex,
    speed: pd.DataFrame,
    observed_mask: pd.DataFrame,
    no_vehicle_mask: pd.DataFrame,
    raw_missing_mask: pd.DataFrame,
    imputation_method: pd.DataFrame,
    outlier_mask: pd.DataFrame,
) -> dict[str, object]:
    total_cells = speed.shape[0] * speed.shape[1]
    observed_cells = int(observed_mask.to_numpy(dtype=bool).sum())
    no_vehicle_cells = int(no_vehicle_mask.to_numpy(dtype=bool).sum())
    raw_missing_cells = int(raw_missing_mask.to_numpy(dtype=bool).sum())
    outlier_cells = int(outlier_mask.to_numpy(dtype=bool).sum())
    missing_cells = int(speed.isna().to_numpy().sum())
    method_counts = (
        imputation_method.stack()
        .value_counts()
        .rename_axis("imputation_method")
        .rename("cells")
        .reset_index()
    )
    return {
        "nodes": len(nodes),
        "timestamps": len(timestamps),
        "total_cells": total_cells,
        "observed_cells": observed_cells,
        "observed_rate": observed_cells / total_cells,
        "no_vehicle_cells": no_vehicle_cells,
        "no_vehicle_rate": no_vehicle_cells / total_cells,
        "raw_missing_cells": raw_missing_cells,
        "raw_missing_rate": raw_missing_cells / total_cells,
        "iqr_outlier_cells": outlier_cells,
        "iqr_outlier_rate": outlier_cells / total_cells,
        "missing_cells": missing_cells,
        "missing_rate": missing_cells / total_cells,
        "method_counts": method_counts,
    }


