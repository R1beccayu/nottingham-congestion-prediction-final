def main() -> None:
    args = parse_args()
    args.common_output_dir.mkdir(parents=True, exist_ok=True)
    args.diagnostics_output_dir.mkdir(parents=True, exist_ok=True)

    nodes = load_nodes(args.node_list)
    node_ids = nodes["node_id"].tolist()
    all_timestamps = expected_timestamps(args.start_date, args.end_date, args.frequency)
    timestamps, timestamp_filter_info = filter_timestamps(
        all_timestamps,
        exclude_weekends=args.exclude_weekends,
        exclude_bank_holidays=args.exclude_bank_holidays,
        bank_holidays=args.bank_holidays,
    )
    args.timestamp_filter_info = timestamp_filter_info
    imputation_stats_timestamps = statistics_timestamps(
        args.imputation_stats_start_date,
        args.imputation_stats_end_date,
        args.frequency,
        timestamps,
        exclude_weekends=args.imputation_stats_exclude_weekends,
        exclude_bank_holidays=not args.include_bank_holidays_in_imputation_stats,
        bank_holidays=args.bank_holidays,
        label="median imputation",
    )
    iqr_stats_timestamps = statistics_timestamps(
        args.iqr_stats_start_date,
        args.iqr_stats_end_date,
        args.frequency,
        timestamps,
        exclude_weekends=args.iqr_stats_exclude_weekends,
        exclude_bank_holidays=not args.include_bank_holidays_in_iqr_stats,
        bank_holidays=args.bank_holidays,
        label="IQR outlier",
    )
    data = read_daily_files(args.input_dir, args.start_date, args.end_date)
    data = data[data["node_id"].isin(node_ids)].copy()

    speed = pivot_matrix(data, timestamps, node_ids, "motorised_mean_speed")
    observed_mask = pivot_matrix(data, timestamps, node_ids, "speed_observed_mask", fill_value=0).astype(int)
    no_vehicle_mask = pivot_matrix(data, timestamps, node_ids, "no_vehicle_flag", fill_value=0).astype(int)
    raw_missing_mask = pivot_matrix(data, timestamps, node_ids, "raw_missing_flag", fill_value=1).astype(int)

    if args.disable_iqr_outlier_filter:
        speed_for_imputation = speed.copy()
        outlier_mask = pd.DataFrame(False, index=speed.index, columns=speed.columns)
        outlier_audit = pd.DataFrame(
            columns=[
                "node_id",
                "observed_values",
                "stats_observed_values",
                "q1",
                "q3",
                "iqr",
                "iqr_multiplier",
                "upper_bound",
                "outlier_count",
                "outlier_rate_observed",
                "max_original_speed",
                "status",
            ]
        )
        outlier_cells = pd.DataFrame(
            columns=[
                "datetime",
                "node_id",
                "original_speed",
                "q1",
                "q3",
                "iqr",
                "iqr_multiplier",
                "upper_bound",
            ]
        )
    else:
        speed_for_imputation, outlier_mask, outlier_audit, outlier_cells = detect_upper_iqr_outliers(
            speed,
            iqr_multiplier=args.iqr_multiplier,
            min_observations=args.min_iqr_observations,
            stats_timestamps=iqr_stats_timestamps,
        )

    valid_observed_mask = (observed_mask.astype(bool) & ~outlier_mask).astype(int)

    speed_imputed, imputation_method = interpolate_speed_matrix(
        speed_for_imputation,
        max_linear_gap=args.max_linear_gap,
        outlier_mask=outlier_mask,
        imputation_stats_timestamps=imputation_stats_timestamps,
    )

    timestamps_out = pd.DataFrame({"datetime": timestamps.strftime("%Y-%m-%d %H:%M:%S")})
    timestamps_out.to_csv(args.common_output_dir / "timestamps.csv", index=False)
    nodes.to_csv(args.common_output_dir / "node_list.csv", index=False)
    speed_imputed.to_csv(args.common_output_dir / "speed_imputed.csv", index=False)
    speed.to_csv(args.diagnostics_output_dir / "speed_raw.csv", index=False)
    valid_observed_mask.to_csv(args.diagnostics_output_dir / "speed_observed_mask.csv", index=False)
    imputation_method.to_csv(args.diagnostics_output_dir / "imputation_method.csv", index=False)
    outlier_mask.astype(int).to_csv(args.diagnostics_output_dir / "iqr_outlier_mask.csv", index=False)
    outlier_audit.to_csv(args.diagnostics_output_dir / "outlier_iqr_audit.csv", index=False)
    outlier_cells.to_csv(args.diagnostics_output_dir / "outlier_iqr_cells.csv", index=False)

    summary = build_run_summary(
        nodes=nodes,
        timestamps=timestamps,
        speed=speed_for_imputation,
        observed_mask=valid_observed_mask,
        no_vehicle_mask=no_vehicle_mask,
        raw_missing_mask=raw_missing_mask,
        imputation_method=imputation_method,
        outlier_mask=outlier_mask,
    )
    write_summary(
        args.diagnostics_output_dir / "speed_model_input_summary.md",
        args,
        nodes,
        timestamps,
        summary,
    )

    print(f"Nodes: {len(nodes)}")
    print(f"Timestamps: {len(timestamps)}")
    print(f"Observed speed cells: {summary['observed_cells']} ({summary['observed_rate']:.2%})")
    print(f"No-vehicle cells: {summary['no_vehicle_cells']} ({summary['no_vehicle_rate']:.2%})")
    print(f"Raw missing cells: {summary['raw_missing_cells']} ({summary['raw_missing_rate']:.2%})")
    print(f"IQR outlier cells removed before imputation: {summary['iqr_outlier_cells']} ({summary['iqr_outlier_rate']:.4%})")
    print("Imputation method counts:")
    print(summary["method_counts"].to_string(index=False))
    print(f"Model inputs: {args.common_output_dir}")
    print(f"Diagnostics: {args.diagnostics_output_dir}")


if __name__ == "__main__":
    main()
